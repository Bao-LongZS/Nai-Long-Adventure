"""Assemble A/N1/N2/C1 renders without cropping or per-candidate normalization.

Use --models A N1 N2 for the neck-selection stage; add C1 after it is saved.
Input PNGs are generated by render_head_neck_comparisons.py, never overwritten.
"""
import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageDraw
from make_spherical_eye_comparisons import font, centered

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "versions/20261006_head_neck_refinement"
CMP = OUT / "comparisons"
ORDER = ("A", "N1", "N2", "C1")
LABELS = {"A": "固定 A / Baseline", "N1": "N1 / 温和颈部", "N2": "N2 / 明显颈部", "C1": "C1 / 选定颈部 + 头壳"}


def digest(path):
    with Path(path).open("rb") as handle:
        result = hashlib.file_digest(handle, "sha256")
    return result.hexdigest()


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8-sig"))


def verify_protocol(models):
    protocol_path = OUT / "render_protocol.json"
    if not protocol_path.exists():
        protocol_path = OUT / "comparisons/camera_protocol.json"
    protocol = read_json(protocol_path)
    if protocol["saved_source_models"]:
        raise ValueError("Rendering protocol reports mutation of source models")
    for model in models:
        source = protocol["sources"][model]
        if digest(source["path"]) != source["sha256"]:
            raise ValueError(f"Render no longer matches saved {model} model")
    grouped = {}
    for record in protocol["files"]:
        if record["model"] not in models:
            continue
        if record["source_sha256"] != protocol["sources"][record["model"]]["sha256"]:
            raise ValueError(f"Mixed model versions: {record['file']}")
        if not (OUT / record["file"]).is_file():
            raise FileNotFoundError(record["file"])
        suffix = Path(record["file"]).name.removeprefix(record["model"] + "_")
        key = (suffix, record["mode"])
        if key in grouped and grouped[key] != record["pose"]:
            raise ValueError(f"Different cameras within comparison {suffix}")
        grouped[key] = record["pose"]
    return protocol


def assemble(models, prefix, views, title, destination, protocol):
    filenames = [f"{model}_{prefix}_{view}.png" for view in views for model in models]
    sizes = set()
    for filename in filenames:
        with Image.open(CMP / filename) as image:
            sizes.add(image.size)
    if len(sizes) != 1:
        raise ValueError(f"Different input image dimensions for {prefix}: {sizes}")
    raw_w, raw_h = sizes.pop()
    width, gutter, margin, header, row_bar, footer = 630, 18, 30, 170, 46, 110
    height = round(raw_h * width / raw_w)
    canvas_width = 2 * margin + len(models) * width + (len(models) - 1) * gutter
    canvas_height = header + len(views) * (height + row_bar + gutter) + footer
    canvas = Image.new("RGB", (canvas_width, canvas_height), "#f0f3f7")
    draw = ImageDraw.Draw(canvas)
    draw.rectangle((0, 0, canvas.width, 108), fill="#17263b")
    draw.text((margin, 20), title, font=font(33), fill="white")
    draw.text((margin, 64), "固定 A 输入 · 同机位 / 同灯光 / 同曝光 / 同像素尺度 · Idle 第 1 帧", font=font(22), fill="#cbd6e6")
    for col, model in enumerate(models):
        centered(draw, (margin + col * (width + gutter) + width / 2, 127), LABELS[model], 24, "#17263b")
    rows = {"front": "0° 正面", "three_quarter": "45° 斜侧", "side": "90° 侧面"}
    for row, view in enumerate(views):
        y = header + row * (height + row_bar + gutter)
        draw.text((margin, y + 5), rows[view], font=font(23), fill="#43566d")
        for col, model in enumerate(models):
            with Image.open(CMP / f"{model}_{prefix}_{view}.png") as original:
                tile = original.convert("RGB").resize((width, height), Image.Resampling.LANCZOS)
            canvas.paste(tile, (margin + col * (width + gutter), y + row_bar))
    draw.text((margin, canvas.height - 95), "保留完整原始画幅，所有列仅作相同显示缩放；没有重新注册相机或按候选眼径归一化。", font=font(22), fill="#43566d")
    if prefix == "body_id":
        draw.text((margin, canvas.height - 58), "白色发光对象 ID 只显示评估后的黄色主体；轮廓不受材质颜色、阴影及高光影响。", font=font(21), fill="#68788c")
    elif 'C1' in models:
        draw.text((margin, canvas.height - 58), "C1 是选定颈部候选上独立测试的头壳修正；采用结论以实际验收与参考复核为准。", font=font(21), fill="#68788c")
    else:
        draw.text((margin, canvas.height - 58), "本次只完成第一阶段下脸—颈部 N1/N2；上部头壳保持固定 A。", font=font(21), fill="#68788c")
    canvas.save(CMP / destination)
    return {"output": destination, "models": models, "inputs": filenames, "raw_size": [raw_w, raw_h], "display_size": [width, height], "crop": None, "per_model_scale": False}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--models", nargs="+", choices=ORDER, default=["A", "N1", "N2"])
    args = parser.parse_args()
    models = [model for model in ORDER if model in args.models]
    protocol = verify_protocol(models)
    records = []
    for prefix, views, title, filename in (
        ("head", ("front", "three_quarter", "side"), "下脸—颈部精修：头部彩色三视图", "comparison_head.png"),
        ("head_gray", ("front", "three_quarter", "side"), "下脸—颈部精修：头部灰模三视图", "comparison_head_gray.png"),
        ("full", ("front",), "下脸—颈部精修：全身正面", "comparison_full.png"),
        ("body_id", ("front", "three_quarter", "side"), "下脸—颈部精修：黄色主体对象 ID", "comparison_body_id.png"),
    ):
        records.append(assemble(models, prefix, views, title, filename, protocol))
    (CMP / "assembly_protocol.json").write_text(json.dumps({"model_order": models, "source_sha256": {model: protocol["sources"][model]["sha256"] for model in models}, "source_hashes_verified": True, "same_camera_poses_verified": True, "panels": records}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("HEAD_NECK_COMPARISON_ASSEMBLY_OK", models)


if __name__ == "__main__":
    main()
